package ru.mirea.kulikov.pr1.classes.task1;

/**
 * Практическая работа 1 «Классы», задание 1 (исправленная версия).
 *
 * Исходная ошибка: в классе A был объявлен только конструктор A(String),
 * поэтому компилятор НЕ создал конструктор по умолчанию, а вызов
 * new A() в классе TestA приводил к ошибке компиляции:
 * "constructor A in class A cannot be applied to given types".
 *
 * Исправление: добавлен безаргументный конструктор A(), а в TestA
 * также показан вызов существующего конструктора A(String).
 *
 * @author Куликов М.М., группа УИБО-03-24
 */
public class A {
    String s;

    /** Безаргументный конструктор (добавлен для исправления ошибки) */
    A() {
        this("Строка по умолчанию");
    }

    /** Конструктор с параметром (был в исходной программе) */
    A(String newS) {
        s = newS;
    }

    public void print() {
        System.out.print(s);
    }
}
